"""
Autonomous Proactive Heartbeat Daemon for Julius.

Runs as a background monitoring daemon that continuously tracks:
- System vitals (disk space, memory pressure, battery level)
- Git repository drift & workspace dirty status
- Scheduled task / loop queues
- Produces proactive alerts and recommendations before problems escalate
"""

from __future__ import annotations

import asyncio
import logging
import os
import shutil
import subprocess
import time
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional

from .system_controller import get_system_controller, SystemVitals

logger = logging.getLogger(__name__)


class AlertSeverity(str, Enum):
    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"


@dataclass
class ProactiveAlert:
    """A proactive alert generated by the background daemon."""
    id: str
    severity: AlertSeverity
    source: str  # "system", "git", "task", "security"
    title: str
    message: str
    suggestion: str = ""
    timestamp: float = field(default_factory=time.time)
    acknowledged: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "severity": self.severity.value,
            "source": self.source,
            "title": self.title,
            "message": self.message,
            "suggestion": self.suggestion,
            "timestamp": self.timestamp,
            "acknowledged": self.acknowledged,
        }

    def format_line(self) -> str:
        icon = "ℹ️" if self.severity == AlertSeverity.INFO else ("⚠️" if self.severity == AlertSeverity.WARNING else "🚨")
        return f"{icon} [{self.source.upper()}] {self.title}: {self.message}"


class ProactiveDaemon:
    """
    Background autonomous executive monitoring system and workspace health.
    """

    def __init__(
        self,
        workspace_root: str = ".",
        heartbeat_interval: float = 30.0,
        on_alert: Optional[Callable[[ProactiveAlert], None]] = None,
        auto_notify: bool = False,
    ) -> None:
        self.workspace_root = Path(workspace_root).resolve()
        self.heartbeat_interval = heartbeat_interval
        self.on_alert = on_alert
        self.auto_notify = auto_notify

        self.system_controller = get_system_controller()
        self.alerts_history: List[ProactiveAlert] = []
        self._is_running = False
        self._task: Optional[asyncio.Task] = None
        self._last_git_check: float = 0.0

        logger.info("ProactiveDaemon initialized (workspace=%s, interval=%.1fs)", self.workspace_root, self.heartbeat_interval)

    # ── Watchers ──────────────────────────────────────────────────────────────

    def check_system_vitals(self) -> List[ProactiveAlert]:
        """Check hardware and OS vitals for abnormal conditions."""
        alerts: List[ProactiveAlert] = []
        vitals = self.system_controller.get_system_vitals()

        # 1. Disk Space Check
        if vitals.disk_free_gb < 10.0 or vitals.disk_percent_used > 92.0:
            alerts.append(
                ProactiveAlert(
                    id=f"alert_disk_{int(time.time())}",
                    severity=AlertSeverity.WARNING if vitals.disk_free_gb >= 5.0 else AlertSeverity.CRITICAL,
                    source="system",
                    title="Low Disk Space",
                    message=f"Root volume has only {round(vitals.disk_free_gb, 1)} GB free ({round(100 - vitals.disk_percent_used)}% remaining).",
                    suggestion="Clean up caches or temporary files with 'df -h' and Julius disk cleanup tools.",
                )
            )

        # 2. Memory Pressure Check
        if vitals.memory_percent > 88.0:
            alerts.append(
                ProactiveAlert(
                    id=f"alert_mem_{int(time.time())}",
                    severity=AlertSeverity.WARNING,
                    source="system",
                    title="High Memory Pressure",
                    message=f"System RAM is at {round(vitals.memory_percent)}% utilization ({round(vitals.memory_used_gb, 1)}/{round(vitals.memory_total_gb, 1)} GB).",
                    suggestion="Check for runaway processes or close unneeded background browser tabs.",
                )
            )

        # 3. Battery Check
        if vitals.battery_percent is not None and not vitals.battery_charging:
            if vitals.battery_percent < 15.0:
                alerts.append(
                    ProactiveAlert(
                        id=f"alert_bat_{int(time.time())}",
                        severity=AlertSeverity.CRITICAL,
                        source="system",
                        title="Critical Battery Level",
                        message=f"Battery is down to {int(vitals.battery_percent)}% and not plugged in.",
                        suggestion="Connect AC power adapter soon to prevent unexpected shutdown.",
                    )
                )

        return alerts

    def check_git_status(self) -> List[ProactiveAlert]:
        """Inspect git repository state for uncommitted changes or branch status."""
        alerts: List[ProactiveAlert] = []
        if not (self.workspace_root / ".git").exists() or not shutil.which("git"):
            return alerts

        try:
            # Check git status short
            res = subprocess.run(
                ["git", "status", "--porcelain"],
                cwd=str(self.workspace_root),
                capture_output=True,
                text=True,
                timeout=2.0,
            )
            if res.returncode == 0:
                lines = [l for l in res.stdout.splitlines() if l.strip()]
                if len(lines) > 25:
                    alerts.append(
                        ProactiveAlert(
                            id=f"alert_git_{int(time.time())}",
                            severity=AlertSeverity.INFO,
                            source="git",
                            title="Large Uncommitted Working Tree",
                            message=f"{len(lines)} uncommitted files modified in workspace.",
                            suggestion="Consider staging or committing logical milestones.",
                        )
                    )
        except Exception as exc:
            logger.debug("Git status check error: %s", exc)

        return alerts

    # ── Daemon Heartbeat Loop ─────────────────────────────────────────────────

    async def _heartbeat_step(self) -> List[ProactiveAlert]:
        """Run a single cycle of proactive health checks."""
        current_alerts: List[ProactiveAlert] = []

        # System health
        sys_alerts = self.check_system_vitals()
        current_alerts.extend(sys_alerts)

        # Git health (every 2 minutes)
        now = time.time()
        if now - self._last_git_check > 120.0:
            self._last_git_check = now
            git_alerts = self.check_git_status()
            current_alerts.extend(git_alerts)

        # Process new alerts
        for alert in current_alerts:
            self.alerts_history.append(alert)
            logger.info("ProactiveDaemon alert: %s", alert.format_line())

            if self.on_alert:
                try:
                    self.on_alert(alert)
                except Exception as cb_err:
                    logger.debug("Alert callback error: %s", cb_err)

            if self.auto_notify and alert.severity in (AlertSeverity.WARNING, AlertSeverity.CRITICAL):
                self.system_controller.send_notification(
                    title=f"Julius: {alert.title}",
                    message=alert.message,
                    sound=True,
                )

        return current_alerts

    async def start(self) -> None:
        """Start the proactive background monitoring loop."""
        if self._is_running:
            return

        self._is_running = True
        logger.info("ProactiveDaemon started")

        while self._is_running:
            try:
                await self._heartbeat_step()
            except asyncio.CancelledError:
                break
            except Exception as exc:
                logger.error("Error in ProactiveDaemon heartbeat: %s", exc)

            try:
                await asyncio.sleep(self.heartbeat_interval)
            except asyncio.CancelledError:
                break

        self._is_running = False
        logger.info("ProactiveDaemon stopped")

    def stop(self) -> None:
        """Stop the proactive monitoring loop."""
        self._is_running = False
        if self._task and not self._task.done():
            self._task.cancel()

    def get_latest_alerts(self, limit: int = 10) -> List[ProactiveAlert]:
        """Retrieve recent alerts."""
        return self.alerts_history[-limit:]


# Global singleton instance
_proactive_daemon: Optional[ProactiveDaemon] = None


def get_proactive_daemon(workspace: str = ".") -> ProactiveDaemon:
    """Get or create the global ProactiveDaemon."""
    global _proactive_daemon
    if _proactive_daemon is None:
        _proactive_daemon = ProactiveDaemon(workspace_root=workspace)
    return _proactive_daemon
