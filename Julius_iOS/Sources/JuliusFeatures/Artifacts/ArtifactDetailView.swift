import SwiftUI
import JuliusCore
import JuliusUI
#if canImport(UIKit)
import UIKit
#elseif canImport(AppKit)
import AppKit
#endif

public struct ArtifactDetailView: View {
    public let artifact: Artifact
    public let onClose: () -> Void
    public let onJumpToChat: () -> Void
    public let onExport: () -> Void

    public init(
        artifact: Artifact,
        onClose: @escaping () -> Void,
        onJumpToChat: @escaping () -> Void = {},
        onExport: @escaping () -> Void = {}
    ) {
        self.artifact = artifact
        self.onClose = onClose
        self.onJumpToChat = onJumpToChat
        self.onExport = onExport
    }

    public var body: some View {
        ZStack {
            ClaudeTheme.bgCanvas
                .ignoresSafeArea()

            VStack(spacing: 0) {
                // Top Header Bar
                HStack {
                    Button(action: onClose) {
                        ZStack {
                            Circle()
                                .fill(Color.clear)
                                .frame(width: 38, height: 38)
                            Circle()
                                .stroke(JuliusTheme.brandGold.opacity(0.35), lineWidth: 1)
                                .frame(width: 38, height: 38)
                            Image(systemName: "xmark")
                                .font(.system(size: 14, weight: .bold))
                                .foregroundColor(JuliusTheme.brandGold)
                        }
                    }

                    Spacer()

                    Text(artifact.title)
                        .font(JuliusTheme.sansBold(size: 16))
                        .foregroundColor(JuliusTheme.textPrimary)
                        .lineLimit(1)

                    Spacer()

                    HStack(spacing: 12) {
                        Button(action: onJumpToChat) {
                            Image(systemName: "bubble.left")
                                .font(.system(size: 16))
                                .foregroundColor(JuliusTheme.brandGold)
                        }
                        Button(action: onExport) {
                            Image(systemName: "square.and.arrow.up")
                                .font(.system(size: 16))
                                .foregroundColor(JuliusTheme.brandGold)
                        }
                    }
                    .padding(.horizontal, 14)
                    .padding(.vertical, 8)
                    .background(JuliusTheme.brandGold.opacity(0.08))
                    .overlay(
                        Capsule().stroke(JuliusTheme.brandGold.opacity(0.3), lineWidth: 1)
                    )
                    .clipShape(Capsule())
                }
                .padding(.horizontal, 16)
                .padding(.vertical, 10)

                // Scrollable Artifact Document
                ScrollView(showsIndicators: true) {
                    VStack(alignment: .leading, spacing: 20) {
                        // Title & Subtitle Header
                        VStack(alignment: .leading, spacing: 10) {
                            Text(artifact.title)
                                .font(ClaudeTheme.sansBold(size: 26))
                                .foregroundColor(ClaudeTheme.textPrimary)
                            Text(artifact.explanation.isEmpty ? "A self-contained production module generated by Julius." : artifact.explanation)
                                .font(ClaudeTheme.sansRegular(size: 16))
                                .foregroundColor(ClaudeTheme.textSecondary)
                                .lineSpacing(4)
                        }

                        // Section 1 Card: Overview / Explanation
                        VStack(alignment: .leading, spacing: 12) {
                            Text("1. Overview")
                                .font(ClaudeTheme.sansBold(size: 18))
                                .foregroundColor(Color(hex: "#7FA8E8"))

                            Text(artifact.explanation.isEmpty ? "A self-contained production module generated by Julius during your reasoning cycle." : artifact.explanation)
                                .font(ClaudeTheme.sansRegular(size: 15))
                                .foregroundColor(ClaudeTheme.textPrimary)
                                .lineSpacing(5)
                        }
                        .padding(18)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .background(ClaudeTheme.surface)
                        .cornerRadius(16)
                        .overlay(
                            RoundedRectangle(cornerRadius: 16)
                                .stroke(ClaudeTheme.borderIdle, lineWidth: 1)
                        )

                        // Section 2 Card: The Code
                        VStack(alignment: .leading, spacing: 14) {
                            HStack {
                                Text("2. The code")
                                    .font(ClaudeTheme.sansBold(size: 18))
                                    .foregroundColor(Color(hex: "#7FA8E8"))
                                Spacer()
                                Button(action: {
                                    #if canImport(UIKit)
                                    UIPasteboard.general.string = artifact.content
                                    #elseif canImport(AppKit)
                                    NSPasteboard.general.clearContents()
                                    NSPasteboard.general.setString(artifact.content, forType: .string)
                                    #endif
                                }) {
                                    HStack(spacing: 4) {
                                        Image(systemName: "doc.on.doc")
                                            .font(.system(size: 12))
                                            .foregroundColor(JuliusTheme.brandGold)
                                        Text("Copy")
                                            .font(JuliusTheme.sansBold(size: 12))
                                            .foregroundColor(JuliusTheme.textPrimary)
                                    }
                                    .padding(.horizontal, 10)
                                    .padding(.vertical, 6)
                                    .background(Color.white.opacity(0.04))
                                    .overlay(
                                        Capsule().stroke(JuliusTheme.brandGold.opacity(0.3), lineWidth: 1)
                                    )
                                    .clipShape(Capsule())
                                }
                            }

                            // Code block with monospaced font
                            ScrollView(.horizontal, showsIndicators: false) {
                                Text(artifact.content)
                                    .font(ClaudeTheme.monospaced(size: 13))
                                    .foregroundColor(Color(hex: "#E0E0E0"))
                                    .lineSpacing(4)
                                    .padding(8)
                            }
                        }
                        .padding(18)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .background(ClaudeTheme.surface)
                        .cornerRadius(16)
                        .overlay(
                            RoundedRectangle(cornerRadius: 16)
                                .stroke(ClaudeTheme.borderIdle, lineWidth: 1)
                        )
                    }
                    .padding(20)
                }
            }
        }
    }
}
